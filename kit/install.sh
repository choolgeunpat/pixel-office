#!/usr/bin/env bash
# Pixel Office installer — adds the Pixel Office hook and a six-person subagent team
# to the current git repository (.claude/), so every Claude Code session in it
# (local or claude.ai/code cloud) streams its activity to your office.
#
#   curl -fsSL https://<your-office>/install.sh | bash
#   curl -fsSL https://<your-office>/install.sh | bash -s -- --team-guide
#
# Options:
#   --team-guide   also append a "delegate to the team" section to CLAUDE.md
#   --no-agents    don't add the six subagents (.claude/agents/*.md)
#   --force        overwrite existing agent files with the same names
#   --uninstall    remove everything this script added
#
# Generated by scripts/build-kit.mjs from kit/ — edit the sources there.
set -euo pipefail

TEAM_GUIDE=0
AGENTS=1
FORCE=0
UNINSTALL=0
for arg in "$@"; do
  case "$arg" in
    --team-guide) TEAM_GUIDE=1 ;;
    --no-agents) AGENTS=0 ;;
    --force) FORCE=1 ;;
    --uninstall) UNINSTALL=1 ;;
    -h | --help) sed -n '2,16p' "$0" 2>/dev/null || true; exit 0 ;;
    *) echo "unknown option: $arg" >&2; exit 2 ;;
  esac
done

say() { printf '\033[1;38;5;209m▸\033[0m %s\n' "$*"; }
ok() { printf '  \033[32m✓\033[0m %s\n' "$*"; }
skip() { printf '  \033[33m•\033[0m %s\n' "$*"; }

root="$(git rev-parse --show-toplevel 2>/dev/null || pwd)"
cd "$root"
say "Pixel Office → $root"

JSON_TOOL=""
if command -v node >/dev/null 2>&1; then JSON_TOOL=node
elif command -v python3 >/dev/null 2>&1; then JSON_TOOL=python3
fi

HOOK_EVENTS='["SessionStart","UserPromptSubmit","PreToolUse","PostToolUse","PostToolUseFailure","SubagentStart","SubagentStop","Stop","Notification","PreCompact","SessionEnd"]'
HOOK_COMMAND='bash "$CLAUDE_PROJECT_DIR/.claude/hooks/pixel-office.sh"'

# settings.json: add (or remove) one async command hook per event; entries are found by
# "pixel-office.sh" in their command, so re-running is idempotent and other hooks are kept.
edit_settings() {
  local mode="$1" file=".claude/settings.json"
  [ -f "$file" ] || echo '{}' >"$file"
  if [ "$JSON_TOOL" = node ]; then
    MODE="$mode" EVENTS="$HOOK_EVENTS" CMD="$HOOK_COMMAND" node -e '
const fs = require("fs");
const f = ".claude/settings.json";
const s = JSON.parse(fs.readFileSync(f, "utf8") || "{}");
const ours = (h) => (h.hooks || []).some((x) => String(x.command || "").includes("pixel-office.sh"));
s.hooks = s.hooks || {};
for (const ev of Object.keys(s.hooks)) {
  s.hooks[ev] = s.hooks[ev].filter((g) => !ours(g));
  if (!s.hooks[ev].length) delete s.hooks[ev];
}
if (process.env.MODE === "add")
  for (const ev of JSON.parse(process.env.EVENTS)) (s.hooks[ev] = s.hooks[ev] || []).push({ hooks: [{ type: "command", command: process.env.CMD, async: true, timeout: 10 }] });
if (!Object.keys(s.hooks).length) delete s.hooks;
fs.writeFileSync(f, JSON.stringify(s, null, 2) + "\n");'
  elif [ "$JSON_TOOL" = python3 ]; then
    MODE="$mode" EVENTS="$HOOK_EVENTS" CMD="$HOOK_COMMAND" python3 -c '
import json, os
f = ".claude/settings.json"
s = json.load(open(f)) if os.path.getsize(f) else {}
ours = lambda g: any("pixel-office.sh" in str(h.get("command", "")) for h in g.get("hooks", []))
hooks = s.setdefault("hooks", {})
for ev in list(hooks):
    hooks[ev] = [g for g in hooks[ev] if not ours(g)]
    if not hooks[ev]: del hooks[ev]
if os.environ["MODE"] == "add":
    for ev in json.loads(os.environ["EVENTS"]):
        hooks.setdefault(ev, []).append({"hooks": [{"type": "command", "command": os.environ["CMD"], "async": True, "timeout": 10}]})
if not hooks: del s["hooks"]
open(f, "w").write(json.dumps(s, indent=2, ensure_ascii=False) + "\n")'
  else
    echo "  ! node or python3 is needed to edit $file. Add this hook to every event in $HOOK_EVENTS by hand:" >&2
    echo "    {\"hooks\":[{\"type\":\"command\",\"command\":\"bash \\\"\$CLAUDE_PROJECT_DIR/.claude/hooks/pixel-office.sh\\\"\",\"async\":true}]}" >&2
    return 1
  fi
}

AGENT_NAMES="designer developer marketer planner reviewer tester"

if [ "$UNINSTALL" = 1 ]; then
  rm -f .claude/hooks/pixel-office.sh && ok "removed .claude/hooks/pixel-office.sh"
  [ -f .claude/settings.json ] && edit_settings remove && ok "removed hooks from .claude/settings.json"
  for n in $AGENT_NAMES; do
    f=".claude/agents/$n.md"
    if [ -f "$f" ] && grep -q "small product team" "$f"; then rm -f "$f" && ok "removed $f"; fi
  done
  if [ -f CLAUDE.md ] && grep -q "pixel-office:team" CLAUDE.md; then
    sed -i.bak '/<!-- pixel-office:team -->/,/<!-- \/pixel-office:team -->/d' CLAUDE.md && rm -f CLAUDE.md.bak && ok "removed team section from CLAUDE.md"
  fi
  say "Pixel Office removed."
  exit 0
fi

mkdir -p .claude/hooks .claude/agents

write() { # write <path> — contents on stdin
  cat >"$1"
}

# ---- hook script
write .claude/hooks/pixel-office.sh <<'PIXEL_OFFICE_EOF'
#!/usr/bin/env bash
# Pixel Office hook — forwards Claude Code hook events to your Pixel Office room.
#
# Reads the hook JSON on stdin and POSTs it to $PIXEL_OFFICE_URL (your room page,
# e.g. https://office.example.com/r/abc123…). Without that variable it does nothing.
# It never blocks or fails Claude: every error is swallowed and it always exits 0.
# Large fields (tool output, file contents) are dropped before sending when node is available;
# the server clips everything again and never stores raw payloads.

url="${PIXEL_OFFICE_URL:-}"
if [ -z "$url" ]; then
  cat >/dev/null
  exit 0
fi

url="${url%%\?*}"
url="${url%%#*}"
case "$url" in
  */r/*) ;;
  *) cat >/dev/null; exit 0 ;;
esac
base="${url%%/r/*}"
key="${url##*/r/}"
key="${key%%/*}"
endpoint="$base/api/r/$key/events"

payload="$(cat)"

if command -v node >/dev/null 2>&1; then
  slim="$(printf '%s' "$payload" | node -e '
let s = "";
process.stdin.on("data", (c) => (s += c)).on("end", () => {
  try {
    const j = JSON.parse(s);
    const clip = (v, n) => (typeof v === "string" && v.length > n ? v.slice(0, n) : v);
    const r = j.tool_response;
    if (r !== undefined) {
      j.tool_response = r && typeof r === "object" ? { is_error: r.is_error, success: r.success, error: clip(r.error, 300) } : {};
    }
    if (j.tool_input && typeof j.tool_input === "object") {
      for (const k of Object.keys(j.tool_input)) {
        const v = j.tool_input[k];
        if (k === "todos") continue;
        if (["content", "old_string", "new_string", "new_source"].includes(k)) delete j.tool_input[k];
        else if (typeof v === "string") j.tool_input[k] = clip(v, 400);
        else if (v && typeof v === "object") delete j.tool_input[k];
      }
    }
    for (const k of ["prompt", "last_assistant_message", "message", "error"]) if (j[k]) j[k] = clip(j[k], 600);
    delete j.transcript_path;
    const path = require("path");
    j._pixel = { repo: j.cwd ? path.basename(j.cwd) : undefined, remote: process.env.CLAUDE_CODE_REMOTE_SESSION_ID || undefined };
    process.stdout.write(JSON.stringify(j));
  } catch {
    process.stdout.write(s);
  }
});' 2>/dev/null)" && [ -n "$slim" ] && payload="$slim"
fi

printf '%s' "$payload" | curl -sS -m 4 -o /dev/null -X POST -H 'content-type: application/json' --data-binary @- "$endpoint" >/dev/null 2>&1 || true
exit 0
PIXEL_OFFICE_EOF
chmod +x .claude/hooks/pixel-office.sh
ok ".claude/hooks/pixel-office.sh"

# ---- settings.json hooks
edit_settings add && ok ".claude/settings.json (hooks: $(echo "$HOOK_EVENTS" | tr -d '[]"' | tr ',' ' '))"

# ---- team (subagents)
if [ "$AGENTS" = 1 ]; then
  if [ -f .claude/agents/designer.md ] && [ "$FORCE" != 1 ]; then skip ".claude/agents/designer.md exists (use --force to replace)"; else
    write .claude/agents/designer.md <<'PIXEL_OFFICE_EOF'
---
name: designer
description: 디자인 담당. Use for UI/UX work — layouts, design tokens, CSS/styling, component look and feel, accessibility and visual polish. Delegate visual and interaction design here.
---

You are the **Designer (디자인)** on a small product team.

- Start from the existing design system (tokens, components, spacing, typography) and extend it consistently.
- Care about hierarchy, contrast, responsive behaviour and accessibility (WCAG AA, focus states, labels).
- Implement designs directly in the code (CSS, components) when asked, keeping changes scoped.
- End with a short summary of the design decisions and the files changed.
PIXEL_OFFICE_EOF
    ok ".claude/agents/designer.md"
  fi
  if [ -f .claude/agents/developer.md ] && [ "$FORCE" != 1 ]; then skip ".claude/agents/developer.md exists (use --force to replace)"; else
    write .claude/agents/developer.md <<'PIXEL_OFFICE_EOF'
---
name: developer
description: 개발 담당. Use for implementing features, fixing bugs and refactoring code according to a plan or task description. Delegate any code-writing work here.
---

You are the **Developer (개발)** on a small product team.

- Read the surrounding code first and follow its conventions (naming, structure, comment density).
- Make the smallest change that fully solves the task; avoid unrelated edits.
- Build and run the relevant fast checks (lint, typecheck, unit tests) before you finish.
- End with a short summary: what changed (files), how you verified it, anything left open.
PIXEL_OFFICE_EOF
    ok ".claude/agents/developer.md"
  fi
  if [ -f .claude/agents/marketer.md ] && [ "$FORCE" != 1 ]; then skip ".claude/agents/marketer.md exists (use --force to replace)"; else
    write .claude/agents/marketer.md <<'PIXEL_OFFICE_EOF'
---
name: marketer
description: 마케팅 담당. Use for launch copy, release notes, changelogs, README and docs wording, landing-page text, SEO and social posts. Delegate any user-facing writing here.
---

You are the **Marketer (마케팅)** on a small product team.

- Understand what actually shipped by reading the plan, diff or docs — never invent features.
- Write clear, benefit-first copy for the target audience; match the product's tone and language.
- Offer 2–3 variants for headlines or posts when useful.
- Put deliverables in files when asked (e.g. `marketing/launch.md`, `CHANGELOG.md`).
- End with a short summary of what you wrote and where.
PIXEL_OFFICE_EOF
    ok ".claude/agents/marketer.md"
  fi
  if [ -f .claude/agents/planner.md ] && [ "$FORCE" != 1 ]; then skip ".claude/agents/planner.md exists (use --force to replace)"; else
    write .claude/agents/planner.md <<'PIXEL_OFFICE_EOF'
---
name: planner
description: 기획 담당. Use for product planning — clarifying requirements, researching the codebase or market, writing PRDs/specs, breaking work into tasks and acceptance criteria. Delegate planning and analysis here before implementation starts.
---

You are the **Planner (기획)** on a small product team.

- Clarify the goal, users and constraints. Read the relevant code and docs before proposing anything.
- Produce a concise plan: scope, non-goals, steps, risks and acceptance criteria.
- When asked, write it to a file (e.g. `docs/PRD.md` or `docs/plan-<topic>.md`).
- Do not implement features yourself; hand clear, testable tasks back to the lead.
- End with a short summary (3–5 lines) of the plan and open questions.
PIXEL_OFFICE_EOF
    ok ".claude/agents/planner.md"
  fi
  if [ -f .claude/agents/reviewer.md ] && [ "$FORCE" != 1 ]; then skip ".claude/agents/reviewer.md exists (use --force to replace)"; else
    write .claude/agents/reviewer.md <<'PIXEL_OFFICE_EOF'
---
name: reviewer
description: 리뷰 담당. Use for code review, security review and final quality checks of a change before it is committed or shipped. Delegate reviews here once work is done.
tools: Read, Grep, Glob, Bash
---

You are the **Reviewer (리뷰)** on a small product team.

- Review the actual diff (`git diff`, changed files) for correctness bugs first, then security, then maintainability.
- For every finding give the file and line, a concrete failure scenario and a suggested fix.
- Separate blocking issues from optional suggestions. Do not edit files yourself.
- End with a verdict: approve / request changes, plus the top issues.
PIXEL_OFFICE_EOF
    ok ".claude/agents/reviewer.md"
  fi
  if [ -f .claude/agents/tester.md ] && [ "$FORCE" != 1 ]; then skip ".claude/agents/tester.md exists (use --force to replace)"; else
    write .claude/agents/tester.md <<'PIXEL_OFFICE_EOF'
---
name: tester
description: 테스트 담당. Use for writing and running tests, reproducing bugs, verifying fixes, and QA of finished work (unit, integration, e2e). Delegate verification here after implementation.
---

You are the **Tester (테스트)** on a small product team.

- Reproduce reported problems first, then verify the fix with the same steps.
- Add or update automated tests that cover the change and its edge cases.
- Run the test suite and report exact results (passed / failed, with the failing output).
- Never skip, disable or weaken a test to get green; report real failures instead.
- End with a short verdict: ready / not ready, and why.
PIXEL_OFFICE_EOF
    ok ".claude/agents/tester.md"
  fi
fi

# ---- CLAUDE.md team guide
if [ "$TEAM_GUIDE" = 1 ]; then
  if [ -f CLAUDE.md ] && grep -q "pixel-office:team" CLAUDE.md; then
    skip "CLAUDE.md already has the team section"
  else
    had=0
    [ -s CLAUDE.md ] && had=1
    { if [ "$had" = 1 ]; then echo; fi; cat <<'PIXEL_OFFICE_EOF'
<!-- pixel-office:team -->
## Team workflow (Pixel Office)

This repo has a six-person team of subagents. Split non-trivial requests and delegate each part to the matching subagent instead of doing everything in the main thread:

| subagent | 담당 | use for |
|---|---|---|
| `planner` | 기획 | requirements, research, PRD/spec, task breakdown |
| `developer` | 개발 | implementation, bug fixes, refactors |
| `tester` | 테스트 | writing/running tests, reproducing and verifying |
| `marketer` | 마케팅 | release notes, README/docs wording, launch copy |
| `designer` | 디자인 | UI/UX, styling, accessibility |
| `reviewer` | 리뷰 | code and security review before committing |

Keep a TodoWrite list for multi-step work. Run independent parts in parallel when possible.
<!-- /pixel-office:team -->
PIXEL_OFFICE_EOF
    } >>CLAUDE.md
    ok "CLAUDE.md (team workflow section)"
  fi
fi

# ---- connection test
echo
if [ -n "${PIXEL_OFFICE_URL:-}" ]; then
  if printf '{"hook_event_name":"SessionStart","session_id":"install-check","source":"install","cwd":"%s"}' "$root" | PIXEL_OFFICE_URL="$PIXEL_OFFICE_URL" bash .claude/hooks/pixel-office.sh && curl -fsS -m 5 -o /dev/null "${PIXEL_OFFICE_URL%%/r/*}/healthz"; then
    ok "connected to ${PIXEL_OFFICE_URL%%/r/*} — check your office page"
  else
    skip "could not reach ${PIXEL_OFFICE_URL%%/r/*} from here (fine if this machine is offline)"
  fi
fi
say "Done! Next steps:"
cat <<'MSG'
  1. Commit and push .claude/ (cloud sessions start from a fresh clone):
       git add .claude CLAUDE.md 2>/dev/null; git commit -m "chore: add Pixel Office" && git push
  2. Give sessions your room address as PIXEL_OFFICE_URL:
       • claude.ai/code: environment → Edit → Environment variables:
           PIXEL_OFFICE_URL=https://<your-office>/r/<room-key>
         and allow <your-office> under Network access → Allowed domains.
       • local: export PIXEL_OFFICE_URL=https://<your-office>/r/<room-key>
  3. Start a new session and watch the team work.
MSG
